#!/usr/bin/env node
// Generates platform token files from cairn.tokens.json. Node standard library only.
//   node design/tokens/build.mjs          write outputs
//   node design/tokens/build.mjs --check  fail if any committed output is stale
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const tokens = JSON.parse(readFileSync(join(here, "cairn.tokens.json"), "utf8"));
const check = process.argv.includes("--check");
const banner = "Generated by design/tokens/build.mjs from design/tokens/cairn.tokens.json. Do not edit.";

const hex = /^#[0-9a-f]{6}$/;
const names = Object.keys(tokens.color.light);
for (const scheme of ["light", "dark"]) {
  const keys = Object.keys(tokens.color[scheme]);
  if (keys.join() !== names.join()) throw new Error(`color.${scheme} must list the same keys in the same order as color.light`);
  for (const [k, v] of Object.entries(tokens.color[scheme])) if (!hex.test(v)) throw new Error(`color.${scheme}.${k} must be #rrggbb`);
}

function luminance(h) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
export function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
}
// Text roles must stay readable on every surface they are drawn on.
const pairs = [["ink", "canvas", 7], ["ink", "surface", 7], ["ink-soft", "sand", 4.5], ["muted", "canvas", 4.5], ["muted", "surface", 4.5], ["muted", "sand", 4.5], ["tertiary", "surface", 3], ["on-accent", "terracotta", 3]];
for (const scheme of ["light", "dark"]) for (const [fg, bg, min] of pairs) {
  const c = contrast(tokens.color[scheme][fg], tokens.color[scheme][bg]);
  if (c < min) throw new Error(`${scheme}: ${fg} on ${bg} contrast ${c.toFixed(2)} < ${min}`);
}

function cssVars(scheme, indent) {
  return names.map((k) => `${indent}--${k}: ${tokens.color[scheme][k]};`).join("\n");
}
function css() {
  const px = (o, prefix) => Object.entries(o).map(([k, v]) => `  --${prefix}${k}: ${v}px;`).join("\n");
  return `/* ${banner} */
:root {
  color-scheme: light;
${cssVars("light", "  ")}
${px(tokens.radius, "r-")}
${px(tokens.space, "space-")}
${px(tokens.layout, "")}
  --font-ui: ${tokens.font.ui};
  --font-serif: ${tokens.font.serif};
  --font-mono: ${tokens.font.mono};
  --article-size: ${tokens.font["article-size"]}px;
  --shadow-pop: ${tokens.shadow.pop};
  --shadow-modal: ${tokens.shadow.modal};
  --ring: ${tokens.shadow.ring};
  --t-fast: ${tokens.motion.fast}ms;
  --t-push: ${tokens.motion.push}ms;
  --t-sheet: ${tokens.motion.sheet}ms;
  --ease: ${tokens.motion.ease};
  --ease-out: ${tokens.motion["ease-out"]};
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${cssVars("dark", "    ")}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${cssVars("dark", "  ")}
}
@media (prefers-reduced-motion: reduce) {
  :root { --t-fast: 1ms; --t-push: 1ms; --t-sheet: 1ms; }
}
`;
}
const camel = (k) => k.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());
function kotlin() {
  const block = (scheme) => names.map((k) => `        val ${camel(k)} = Color(0xFF${tokens.color[scheme][k].slice(1).toUpperCase()})`).join("\n");
  const dims = (o) => Object.entries(o).map(([k, v]) => `    val ${camel(k)} = ${v}.dp`).join("\n");
  return `// ${banner}
package com.alpenl.cairn.share.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

object CairnTokens {
    object Light {
${block("light")}
    }

    object Dark {
${block("dark")}
    }

    object Radius {
${dims(tokens.radius).replace(/^/gm, "    ")}
    }

    object Space {
${Object.entries(tokens.space).map(([k, v]) => `        val S${k} = ${v}.dp`).join("\n")}
    }

    const val MotionFastMs = ${tokens.motion.fast}
    const val MotionPushMs = ${tokens.motion.push}
    const val MotionSheetMs = ${tokens.motion.sheet}
}
`;
}
const outputs = [
  ["design/tokens/dist/tokens.css", css()],
  ["browser-extension/src/tokens.css", css()],
  ["android/app/src/main/java/com/alpenl/cairn/share/ui/theme/CairnTokens.kt", kotlin()],
];
let stale = 0;
for (const [path, content] of outputs) {
  const target = join(root, path);
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== content) { stale++; console.error(`stale: ${path}`); }
    continue;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
  console.log(`wrote ${relative(root, target)}`);
}
if (stale) { console.error("Run: node design/tokens/build.mjs"); process.exit(1); }
if (check) console.log(`${outputs.length} token outputs are current`);
